/** Load a config file from backend/config (cached). @return array<string,mixed> */
function config(string $name): array
{
    static $cache = [];
    if (!isset($cache[$name])) {
        $file = BASE_PATH . '/config/' . basename($name) . '.php';
        $cache[$name] = is_file($file) ? (array) require $file : [];
    }
    return $cache[$name];
}

/** Any stored setting (website or business), with config/business.php defaults. */
function setting(string $key, ?string $default = null): string
{
    return App\Core\Settings::get($key, $default);
}

/** Is a paid feature unlocked on the current plan? (config/plans.php) */
function feature(string $feature): bool
{
    return App\Core\License::has($feature);
}

/** May the signed-in admin use this permission? (config/permissions.php) */
function can(string $permission): bool
{
    return App\Core\Gate::can($permission);
}

/** Digits-only phone for wa.me — 10-digit Indian numbers get the 91 prefix. */
function wa_phone(?string $phone): string
{
    $d = preg_replace('/\D+/', '', (string) $phone) ?? '';
    if (strlen($d) === 11 && str_starts_with($d, '0')) {
        $d = substr($d, 1);
    }
    return strlen($d) === 10 ? '91' . $d : $d;
}

/** https://wa.me/… link with a pre-filled message (empty phone → share picker). */
function wa_link(?string $phone, string $text = ''): string
{
    $p = wa_phone($phone);
    return 'https://wa.me/' . $p . ($text !== '' ? '?text=' . rawurlencode($text) : '');
}

/** ₹15,999.50 — two decimals (for invoices / receipts). */
function inr2(int|float|string|null $amount): string
{
    if ($amount === null || $amount === '') {
        return '—';
    }
    $amount = round((float) $amount, 2);
    $neg = $amount < 0;
    $int = inr(abs((int) floor(abs($amount))));
    $paise = (int) round((abs($amount) - floor(abs($amount))) * 100);
    return ($neg ? '−' : '') . $int . '.' . str_pad((string) $paise, 2, '0', STR_PAD_LEFT);
}

/** "12 Nov 2026" (date only). */
function nice_day(?string $d): string
{
    if (!$d) {
        return '—';
    }
    $ts = strtotime($d);
    return $ts ? date('j M Y', $ts) : '—';
}

/** Amount in Indian words: "Rupees Fifteen Thousand Nine Hundred Ninety Nine Only". */
function amount_in_words(int|float|string $amount): string
{
    $amount = round((float) $amount, 2);
    $rupees = (int) floor($amount);
    $paise = (int) round(($amount - $rupees) * 100);
    $ones = ['', 'One', 'Two', 'Three', 'Four', 'Five', 'Six', 'Seven', 'Eight', 'Nine', 'Ten', 'Eleven', 'Twelve',
             'Thirteen', 'Fourteen', 'Fifteen', 'Sixteen', 'Seventeen', 'Eighteen', 'Nineteen'];
    $tens = ['', '', 'Twenty', 'Thirty', 'Forty', 'Fifty', 'Sixty', 'Seventy', 'Eighty', 'Ninety'];
    $two = static fn (int $n): string => $n < 20 ? $ones[$n] : trim($tens[intdiv($n, 10)] . ' ' . $ones[$n % 10]);
    $three = static fn (int $n): string => trim(($n >= 100 ? $ones[intdiv($n, 100)] . ' Hundred ' : '') . $two($n % 100));
    $words = static function (int $n) use ($two, $three): string {
        if ($n === 0) {
            return 'Zero';
        }
        $out = [];
        foreach ([[10000000, 'Crore'], [100000, 'Lakh'], [1000, 'Thousand']] as [$div, $name]) {
            if ($n >= $div) {
                $q = intdiv($n, $div);
                $out[] = ($q >= 100 ? $three($q) : $two($q)) . ' ' . $name;
                $n %= $div;
            }
        }
        if ($n > 0) {
            $out[] = $three($n);
        }
        return implode(' ', $out);
    };
    $s = 'Rupees ' . $words($rupees);
    if ($paise > 0) {
        $s .= ' and ' . $two($paise) . ' Paise';
    }
    return $s . ' Only';
}

/** Small status badge: <?= status_badge('confirmed') ?> (colours in app.css .rth-status-*). */
function status_badge(?string $status, ?string $label = null): string
{
    $status = (string) $status;
    $label ??= ucwords(str_replace(['_', '-'], ' ', $status));
    return '<span class="badge rth-status rth-status-' . e(preg_replace('/[^a-z0-9_-]/', '', strtolower($status))) . '">' . e($label) . '</span>';
}
