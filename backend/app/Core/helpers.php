/** HTML-escape. ALWAYS use for any dynamic value printed in a template. */
function e(mixed $value): string
{
    return htmlspecialchars((string) ($value ?? ''), ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
}

/** Absolute-path URL inside the admin app (supports installs in a sub-folder via APP_BASE_PATH). */
function url(string $path = '/'): string
{
    $base = rtrim((string) Env::get('APP_BASE_PATH', ''), '/');
    return $base . '/' . ltrim($path, '/');
}

/** Versioned asset URL (cache-busting by file mtime). */
function asset(string $path): string
{
    $path = '/' . ltrim($path, '/');
    $file = PUBLIC_PATH . $path;
    $v = is_file($file) ? '?v=' . filemtime($file) : '';
    return url($path) . $v;
}

/**
 * Turn a stored image path into a full URL for previews in the admin.
 * "/uploads/…" → served by this backend; "/images/…" → served by the website (WEBSITE_URL).
 */
function media_url(?string $path): string
{
    if ($path === null || $path === '') {
        return '';
    }
    if (preg_match('#^https?://#', $path)) {
        return $path;
    }
    if (str_starts_with($path, '/uploads/')) {
        return rtrim((string) Env::get('APP_URL', ''), '/') . $path;
    }
    return rtrim((string) Env::get('WEBSITE_URL', ''), '/') . $path;
}

function csrf_token(): string
{
    return Csrf::token();
}

function csrf_field(): string
{
    return '<input type="hidden" name="_token" value="' . e(Csrf::token()) . '">';
}

function method_field(string $method): string
{
    return '<input type="hidden" name="_method" value="' . e(strtoupper($method)) . '">';
}

function old(string $key, mixed $default = ''): mixed
{
    return Flash::old($key, $default);
}

/** Validation error for a field (or null). */
function error_for(string $key): ?string
{
    return Flash::errors()[$key] ?? null;
}

/** Bootstrap "is-invalid" helper for inputs. */
function invalid(string $key): string
{
    return error_for($key) ? ' is-invalid' : '';
}

function partial(string $view, array $data = []): string
{
    return View::partial($view, $data);
}

/** ₹15,999 (Indian grouping) */
function inr(int|float|null $amount): string
{
    if ($amount === null) {
        return '—';
    }
    $n = (string) (int) round((float) $amount);
    $last3 = substr($n, -3);
    $rest = substr($n, 0, -3);
    if ($rest !== '') {
        $rest = preg_replace('/\B(?=(\d{2})+(?!\d))/', ',', $rest);
        return '₹' . $rest . ',' . $last3;
    }
    return '₹' . $last3;
}

function str_limit(?string $s, int $n = 80): string
{
    $s = (string) $s;
    return mb_strlen($s) > $n ? mb_substr($s, 0, $n - 1) . '…' : $s;
}

/** "12 Nov 2026, 4:05 pm" */
function nice_date(?string $dt): string
{
    if (!$dt) {
        return '—';
    }
    $ts = strtotime($dt);
    return $ts ? date('j M Y, g:i a', $ts) : '—';
}

/** Is the current path inside $prefix? (sidebar active state) */
function nav_active(string $prefix): bool
{
    $path = '/' . trim((string) parse_url($_SERVER['REQUEST_URI'] ?? '/', PHP_URL_PATH), '/');
    $base = rtrim((string) Env::get('APP_BASE_PATH', ''), '/');
    if ($base !== '' && str_starts_with($path, $base)) {
        $path = substr($path, strlen($base)) ?: '/';
    }
    return $prefix === '/' ? $path === '/' : str_starts_with($path, $prefix);
}

